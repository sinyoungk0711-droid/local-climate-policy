const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const source = fs.readFileSync('frontend/js/app.js', 'utf8');
const elements = new Map();
const ne = id => { if (!elements.has(id)) elements.set(id, {checked:true}); return elements.get(id); };
const checks = [{checked:true}, {checked:true}];
const state = {facts:true,draft:true,compare:true,review:true,approved:true};
const context = vm.createContext({ne, $$:()=>checks, nw:state, newsRevision:0});
vm.runInContext(source.slice(source.indexOf('function invalidateReview(){'), source.indexOf('function nrestore(){')), context);
vm.runInContext('invalidateReview()', context);
assert.equal(state.compare, false);
assert.equal(state.approved, false);
assert.equal(ne('editorApproval').checked, false);
assert.ok(checks.every(c=>!c.checked));
vm.runInContext('invalidateFacts()', context);
assert.equal(state.facts, false);
assert.equal(state.draft, false);
assert.equal(ne('checkSource').checked, false);
assert.equal(context.newsRevision, 2);
console.log('Workflow invalidation checks passed');
